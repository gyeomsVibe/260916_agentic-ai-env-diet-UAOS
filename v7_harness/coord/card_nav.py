"""U331: companion cards + card navigation map for the three UAOS tools (spec: U329 notes section 9.6).

Files (all under `<project>/.coord/nav/`):
- `<ID>.json`     one per card, written ONLY by its owner tool (atomic replace). Companion cards `<ID>.<tool>` are
                  created by the conductor at primary-card open, then owned/updated by the companion's tool.
- `card_map.json` regenerated by the conductor from the per-card files (never edited by hand).
- `ids.json`      atomic card-ID registry (allocation + duplicate rejection), guarded by an O_EXCL lock file.
- `events.jsonl`  append-only signal log, appended under the same lock style (Windows loses concurrent appends otherwise).
- `.seen_<tool>.json` is not used; the per-prompt hook keeps its cursor inside desk_delta's cursor file.

Worst-case rules (each has a test in tests/test_u331_companion_nav.py):
- a card whose last signal is older than STALE_S (60 s, spec 9.4-1) reads as UNKNOWN and is never actionable;
- companions are never opened for tools that are not ACTIVE with a fresh heartbeat; at most MAX_OPEN_COMPANIONS (3)
  per tool are open, the rest are QUEUED and promoted when one closes;
- two cards may not share an ID; two live cards owning one file, or the same nature+scope, are reported as overlaps.
"""
from __future__ import annotations

import json
import os
import re
import time
import uuid
from pathlib import Path
from typing import Any

from .presence import PresenceRejected, _tool_lock, read as read_presence, replace_with_retry

NAV_DIR = Path(".coord") / "nav"
TOOLS = ("codex", "claude", "antigravity")
ALIASES = {"agy": "antigravity"}
SHORT = {"antigravity": "agy"}
# Spec 9.4-1: a presence/progress signal is valid for 60 s; older means UNKNOWN, not actionable.
STALE_S = 60.0
# Spec 9.4-1: content reply deadline for a companion's opinion.
COMPANION_DUE_S = 120.0
# Spec 9.6 failure table: 3 open companions per tool, the rest queue (a card x2 explosion would flood each tool).
MAX_OPEN_COMPANIONS = 3
STATES = ("READY", "RUNNING", "WAITING", "BLOCKED", "DONE", "QUEUED", "UNKNOWN")
OPEN_STATES = ("READY", "RUNNING", "WAITING", "BLOCKED", "QUEUED")
CARD_ID_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,31}(\.[a-z]{2,12})?$")
STAGES = 11
MAX_HOOK_LINES = 4
# Fields a card file may carry; anything else passed to write_card is rejected so the map stays parseable.
FIELDS = ("title", "nature", "lane", "priority", "state", "owner", "owned_files", "scope", "primary", "companions",
          "depends_on", "stage", "progress", "waits", "next_action", "acceptance", "plan_rev", "result", "role",
          "created_by")
# Primary-card nature -> companion roles (spec 9.6 rule 2). Index 0 goes to the first eligible tool, index 1 to the second.
ROLES = {
    "implementation": (("VERIFY_AUDIT", "review + counterexample audit of the primary's diff and tests"),
                       ("ARCH_DESIGN", "Stage 0 evidence: cite official docs/GitHub for the primary's design")),
    "design": (("VERIFY_AUDIT", "counterexample hunt against the primary's design"),
               ("ARCH_DESIGN", "implementation-feasibility check of the primary's design")),
}


class NavRejected(Exception):
    """A nav write was refused (duplicate ID, foreign owner, bad field); the reason is the message."""


class DuplicateCardId(NavRejected):
    pass


def canonical(tool: str) -> str:
    name = str(tool or "").strip().lower()
    return ALIASES.get(name, name)


def short(tool: str) -> str:
    return SHORT.get(tool, tool)


def nav_dir(project: Path | str) -> Path:
    return Path(project) / NAV_DIR


def _card_path(project: Path | str, card_id: str) -> Path:
    if not CARD_ID_RE.fullmatch(card_id or ""):
        raise NavRejected(f"bad card id: {card_id!r}")
    return nav_dir(project) / f"{card_id}.json"


def _atomic_write(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    replace_with_retry(tmp, path)


def _read_json(path: Path) -> dict[str, Any] | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def _locked(path: Path):
    """presence's O_EXCL lock; a timeout becomes NavRejected so callers fail closed instead of writing blind."""
    class _Ctx:
        def __enter__(self_inner):
            self_inner._cm = _tool_lock(path)
            try:
                return self_inner._cm.__enter__()
            except PresenceRejected as exc:
                raise NavRejected(f"NAV_LOCK_TIMEOUT {path.name}") from exc

        def __exit__(self_inner, *exc):
            return self_inner._cm.__exit__(*exc)
    return _Ctx()


def log_event(project: Path | str, row: dict[str, Any]) -> None:
    """Locked append: concurrent bare appends lose lines on Windows (house rule)."""
    path = nav_dir(project) / "events.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    with _locked(path):
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")


# ---------------------------------------------------------------- ID allocation

def _plan_floor(project: Path) -> int:
    """Highest U-number already named in PLAN.md, so a fresh registry never re-issues a PLAN card number."""
    try:
        text = (Path(project) / ".coord" / "PLAN.md").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return 0
    nums = [int(m) for m in re.findall(r"\bU(\d{1,5})\b", text)]
    return max(nums, default=0)


def allocate_card_id(project: Path | str, *, owner: str, title: str = "", requested: str = "",
                     branch: str = "", prefix: str = "U") -> str:
    """Atomically issue the next card ID, or claim `requested`; a taken ID with another owner/branch is rejected.

    Receipt: Antigravity's `agy/u327-collab-failover-v32` and Claude's model router both used U327.
    The same (owner, branch) asking again for its own ID is idempotent.
    """
    project = Path(project)
    owner = canonical(owner)
    if owner not in TOOLS:
        raise NavRejected(f"unknown owner tool: {owner!r}")
    reg_path = nav_dir(project) / "ids.json"
    reg_path.parent.mkdir(parents=True, exist_ok=True)
    with _locked(reg_path):
        reg = _read_json(reg_path) or {}
        ids = reg.get("ids") if isinstance(reg.get("ids"), dict) else {}
        if requested:
            if not CARD_ID_RE.fullmatch(requested) or "." in requested:
                raise NavRejected(f"bad card id: {requested!r}")
            taken = ids.get(requested)
            if taken and not (taken.get("owner") == owner and taken.get("branch") == branch):
                raise DuplicateCardId(f"DUPLICATE_CARD_ID {requested} already owned by {taken.get('owner')}"
                                      f" on {taken.get('branch') or '-'}")
            card_id = requested
        else:
            nums = [int(m.group(1)) for k in ids if (m := re.fullmatch(rf"{re.escape(prefix)}(\d+)", k))]
            card_id = f"{prefix}{max(nums + [_plan_floor(project)], default=0) + 1}"
        ids[card_id] = {"owner": owner, "branch": branch, "title": title, "at": time.time()}
        _atomic_write(reg_path, {"ids": ids})
    return card_id


# ---------------------------------------------------------------- card files

def read_card(project: Path | str, card_id: str) -> dict[str, Any] | None:
    return _read_json(_card_path(project, card_id))


def list_cards(project: Path | str) -> list[dict[str, Any]]:
    out = []
    directory = nav_dir(project)
    if not directory.is_dir():
        return out
    for path in sorted(directory.glob("*.json")):
        if path.name in ("ids.json", "card_map.json") or path.name.startswith("."):
            continue
        data = _read_json(path)
        if data and data.get("id"):
            out.append(data)
    return out


def _write_card(project: Path | str, card_id: str, owner: str, fields: dict[str, Any], *, now: float | None,
                enforce_owner: bool) -> dict[str, Any]:
    owner = canonical(owner)
    if owner not in TOOLS:
        raise NavRejected(f"unknown owner tool: {owner!r}")
    bad = [k for k in fields if k not in FIELDS]
    if bad:
        raise NavRejected(f"unknown nav field(s): {bad}")
    if fields.get("state") is not None and fields["state"] not in STATES:
        raise NavRejected(f"bad state: {fields['state']!r}")
    moment = time.time() if now is None else now
    path = _card_path(project, card_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    with _locked(path):
        record = _read_json(path) or {"id": card_id, "state": "READY", "owner": {"tool": owner}, "created_at": moment}
        current = (record.get("owner") or {}).get("tool")
        if enforce_owner and current and current != owner:
            raise NavRejected(f"NOT_OWNER {card_id} is owned by {current}, not {owner}")
        for key, value in fields.items():
            if key == "owner":
                record["owner"] = {**(record.get("owner") or {}), **value, "tool": owner}
            else:
                record[key] = value
        record["owner"].setdefault("tool", owner)
        record["last_signal_at"] = moment
        _atomic_write(path, record)
    log_event(project, {"at": moment, "card": card_id, "tool": owner, "state": record.get("state")})
    return record


def write_card(project: Path | str, card_id: str, owner_tool: str, *, now: float | None = None,
               **fields: Any) -> dict[str, Any]:
    """Owner-only update (atomic replace). A different tool's write is rejected with NOT_OWNER."""
    return _write_card(project, card_id, owner_tool, fields, now=now, enforce_owner=True)


def signal(project: Path | str, card_id: str, owner_tool: str, *, now: float | None = None) -> dict[str, Any]:
    """Heartbeat with no field change: keeps the card out of UNKNOWN."""
    return write_card(project, card_id, owner_tool, now=now)


def effective_state(card: dict[str, Any], now: float | None = None) -> str:
    """STALE_S without a signal -> UNKNOWN (not actionable), except a card already DONE."""
    moment = time.time() if now is None else now
    state = card.get("state") or "UNKNOWN"
    if state == "DONE":
        return "DONE"
    try:
        age = moment - float(card.get("last_signal_at"))
    except (TypeError, ValueError):
        return "UNKNOWN"
    return "UNKNOWN" if age > STALE_S else state


def is_actionable(card: dict[str, Any], now: float | None = None) -> bool:
    return effective_state(card, now) in ("READY", "RUNNING", "WAITING")


# ---------------------------------------------------------------- overlap detection

def _group(card: dict[str, Any]) -> str:
    return str(card.get("primary") or card.get("id"))


def detect_overlaps(cards: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Warn when two live cards of different groups own one file or share nature+scope.

    A primary and its own companions are one group, so a companion never collides with its primary.
    """
    live = [c for c in cards if c.get("state") not in ("DONE",)]
    warnings: list[dict[str, Any]] = []
    for i, a in enumerate(live):
        for b in live[i + 1:]:
            if _group(a) == _group(b):
                continue
            files = sorted(set(a.get("owned_files") or []) & set(b.get("owned_files") or []))
            if files:
                warnings.append({"kind": "FILE_OVERLAP", "cards": [a["id"], b["id"]], "files": files})
            if a.get("scope") and a.get("scope") == b.get("scope") and a.get("nature") == b.get("nature"):
                warnings.append({"kind": "NATURE_SCOPE_OVERLAP", "cards": [a["id"], b["id"]],
                                 "nature": a.get("nature"), "scope": a.get("scope")})
    return warnings


def regenerate_map(project: Path | str, *, now: float | None = None) -> dict[str, Any]:
    """Conductor-only: rebuild card_map.json from the per-card files (a lost map is just rebuilt)."""
    moment = time.time() if now is None else now
    cards = list_cards(project)
    entries = []
    for card in cards:
        entries.append({**card, "effective_state": effective_state(card, moment),
                        "actionable": is_actionable(card, moment)})
    doc = {"generated_at": moment, "stale_after_s": STALE_S, "cards": entries, "overlaps": detect_overlaps(cards)}
    _atomic_write(nav_dir(project) / "card_map.json", doc)
    return doc


# ---------------------------------------------------------------- companion cards

def _fresh_active(project: Path | str, tool: str, now: float, fresh_s: float) -> bool:
    info = read_presence(Path(project), tool, now=now)
    if info.get("state") != "ACTIVE":
        return False
    try:
        from datetime import datetime
        observed = datetime.fromisoformat(str(info.get("observed_at"))).timestamp()
    except (TypeError, ValueError):
        return False
    return now - observed <= fresh_s


def _open_count(cards: list[dict[str, Any]], tool: str) -> int:
    return sum(1 for c in cards if c.get("nature") == "companion" and (c.get("owner") or {}).get("tool") == tool
               and c.get("state") in ("READY", "RUNNING", "WAITING", "BLOCKED"))


def _create_companion(project: Path, primary: dict[str, Any], tool: str, index: int, moment: float,
                      cards: list[dict[str, Any]]) -> dict[str, Any]:
    primary_id = primary["id"]
    primary_tool = (primary.get("owner") or {}).get("tool")
    roles = ROLES.get(str(primary.get("nature")), ROLES["implementation"])
    lane, text = roles[min(index, len(roles) - 1)]
    state = "QUEUED" if _open_count(cards, tool) >= MAX_OPEN_COMPANIONS else "READY"
    return _write_card(project, f"{primary_id}.{short(tool)}", tool, {
        "title": f"{primary.get('title', primary_id)} [companion]", "nature": "companion", "lane": lane,
        "priority": primary.get("priority"), "state": state, "primary": primary_id, "owned_files": [],
        "scope": primary.get("scope"), "role": text, "plan_rev": primary.get("plan_rev", 0),
        "next_action": {short(tool): f"{text}; emit opinion/tests/evidence only, never edit primary files"},
        "waits": [{"what": "content reply", "whom": short(primary_tool or ""),
                   "deadline_at": moment + COMPANION_DUE_S, "fallback": "abstain; primary proceeds"}],
        "created_by": "conductor", "acceptance": primary.get("acceptance"),
    }, now=moment, enforce_owner=False)


def open_companions(project: Path | str, primary_id: str, *, now: float | None = None,
                    fresh_s: float = STALE_S) -> list[dict[str, Any]]:
    """Open `<primary>.<tool>` for each other tool that is ACTIVE with a fresh heartbeat (never for LIMITED/ABSENT/stale).

    Tool over its cap of open companions gets the card as QUEUED. Companions own no files: opinions/tests/evidence only.
    Idempotent: an existing companion is kept (use refresh_companions to update it on a re-plan).
    """
    project = Path(project)
    moment = time.time() if now is None else now
    primary = read_card(project, primary_id)
    if not primary:
        raise NavRejected(f"NO_PRIMARY {primary_id}")
    if "." in primary_id or primary.get("nature") == "companion":
        return []  # companions of companions would multiply cards without bound
    if primary.get("state") == "DONE":
        return []  # a finished primary gets no new companion windows
    primary_tool = (primary.get("owner") or {}).get("tool")
    existing = {c["id"]: c for c in list_cards(project)}
    eligible = [t for t in TOOLS if t != primary_tool and _fresh_active(project, t, moment, fresh_s)]
    opened = []
    for index, tool in enumerate(eligible):
        cid = f"{primary_id}.{short(tool)}"
        if cid in existing and existing[cid].get("state") != "DONE":
            continue
        record = _create_companion(project, primary, tool, index, moment, list(existing.values()))
        existing[cid] = record
        opened.append(record)
    links = sorted(set(primary.get("companions") or []) | {c["id"] for c in opened})
    if links != sorted(primary.get("companions") or []):
        write_card(project, primary_id, primary_tool, companions=links, now=moment)
    return opened


def _promote_queue(project: Path | str, tool: str, now: float) -> list[str]:
    cards = list_cards(project)
    room = MAX_OPEN_COMPANIONS - _open_count(cards, tool)
    promoted = []
    for card in sorted((c for c in cards if c.get("state") == "QUEUED" and (c.get("owner") or {}).get("tool") == tool),
                       key=lambda c: c.get("created_at", 0)):
        if room <= 0:
            break
        _write_card(project, card["id"], tool, {"state": "READY"}, now=now, enforce_owner=False)
        promoted.append(card["id"])
        room -= 1
    return promoted


def _release_window(project: Path | str, cid: str, tool: str, now: float) -> None:
    """U331-D: a finished companion releases its conversation window; best effort, a missing window is fine."""
    try:
        from .windows import release_window

        release_window(Path(project), cid, tool, now=now, reason="companion_done")
    except Exception:  # noqa: BLE001 - closing the nav card must not fail on window bookkeeping
        pass


def close_companions(project: Path | str, primary_id: str, result: str, *, now: float | None = None) -> list[str]:
    """Primary finished: every open companion gets a one-line result and DONE; queued ones are promoted."""
    moment = time.time() if now is None else now
    closed, tools = [], set()
    for card in list_cards(project):
        if card.get("nature") == "companion" and card.get("primary") == primary_id and card.get("state") != "DONE":
            tool = (card.get("owner") or {}).get("tool")
            _write_card(project, card["id"], tool, {"state": "DONE", "result": " ".join(str(result).split())[:200]},
                        now=moment, enforce_owner=False)
            closed.append(card["id"])
            tools.add(tool)
            _release_window(project, card["id"], tool, moment)
    for tool in tools:
        _promote_queue(project, tool, moment)
    return closed


def finish_primary(project: Path | str, primary_id: str, owner_tool: str, result: str, *,
                   now: float | None = None) -> list[str]:
    write_card(project, primary_id, owner_tool, state="DONE", result=result, progress=100, now=now)
    return close_companions(project, primary_id, result, now=now)


def refresh_companions(project: Path | str, primary_id: str, *, now: float | None = None,
                       next_action: str = "") -> list[str]:
    """Primary re-planned: bump plan_rev on every open companion, reset their deadline, add missing ones."""
    moment = time.time() if now is None else now
    primary = read_card(project, primary_id)
    if not primary:
        raise NavRejected(f"NO_PRIMARY {primary_id}")
    rev = int(primary.get("plan_rev") or 0) + 1
    write_card(project, primary_id, (primary.get("owner") or {}).get("tool"), plan_rev=rev, now=moment)
    touched = []
    for card in list_cards(project):
        if card.get("nature") == "companion" and card.get("primary") == primary_id and card.get("state") != "DONE":
            tool = (card.get("owner") or {}).get("tool")
            fields: dict[str, Any] = {"plan_rev": rev, "waits": [{
                "what": "re-plan review", "whom": short((primary.get("owner") or {}).get("tool") or ""),
                "deadline_at": moment + COMPANION_DUE_S, "fallback": "abstain; primary proceeds"}]}
            if next_action:
                fields["next_action"] = {short(tool): next_action}
            _write_card(project, card["id"], tool, fields, now=moment, enforce_owner=False)
            touched.append(card["id"])
    open_companions(project, primary_id, now=moment)
    return touched


# ---------------------------------------------------------------- companion conversation windows (U331-A/B)

# (stage no., slot name, label, Workers line, Output line). The "## Stage N - <name>" headings and the `Workers:` line
# are what card_pipeline.missing_slots demands; a companion manual without them is refused by `coord window`.
STAGE_TEXT = (
    ("1", "Research", "Web Deep Research", "conductor web search (official docs / GitHub URL); Ollama local_draft; "
     "Antigravity source audit", "evidence for the primary's claims, as one note"),
    ("2", "MIA", "11-Stage Canonical Frame", "conductor 11-stage flow; Ollama local_read_map; Antigravity design audit",
     "the companion's one-paragraph frame of the collaboration"),
    ("3", "Execute", "Opinion and tests only", "Ollama (pilot run, worker: local) first; Antigravity for multi-file work",
     "opinion / counterexample tests / evidence; NEVER edit the primary card's files"),
    ("4", "Verify", "Final Verification", "fixed acceptance + full suite; Antigravity review (pilot review --reviewer agy)",
     "one-line result relayed to the primary card"),
)


def _plan_row(project: Path, primary_id: str) -> str:
    try:
        text = (Path(project) / ".coord" / "PLAN.md").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    for line in text.splitlines():
        if line.lstrip().startswith("|") and re.search(rf"\b{re.escape(primary_id)}\b", line):
            return line.strip()[:600]
    return ""


def companion_manual(project: Path | str, companion: dict[str, Any]) -> str:
    """Contract manual for a companion window, built from the PLAN row and the nav card (U331-B).

    It carries the four stage headings with a `Workers:` line each, so `card_pipeline.missing_slots` is empty and
    `coord window` never answers MANUAL_MISSING_SLOTS for a companion.
    """
    cid = companion["id"]
    primary_id = str(companion.get("primary") or cid.split(".")[0])
    primary = read_card(project, primary_id) or {}
    owner = short((primary.get("owner") or {}).get("tool") or "?")
    out = [f"# {cid} contract manual - {companion.get('title') or primary_id}", "",
           f"Work ID: {cid}. Companion of {primary_id}: handle ONLY the collaboration on {primary_id}; its owner "
           f"({owner}) keeps all edits. Role: {companion.get('role', '')}",
           "", "## Receipt", f"- PLAN row: {_plan_row(Path(project), primary_id) or '(no PLAN row)'}",
           f"- primary nav: nature={primary.get('nature')} lane={primary.get('lane')} state={primary.get('state')} "
           f"stage={primary.get('stage')} files={','.join(primary.get('owned_files') or []) or '-'}",
           f"- acceptance: {primary.get('acceptance') or '(see primary card)'}", ""]
    for n, name, label, workers, output in STAGE_TEXT:
        out += [f"## Stage {n} - {name} ({label})", f"Workers: {workers}", f"Output: {output}", ""]
    out += ["## Contract (measurable)",
            f"Reply to {primary_id}'s owner within {int(COMPANION_DUE_S)} s of a letter; silence is abstention.", "",
            "## Allowed files", "none (opinions, tests and evidence under .work/ only)", "",
            "## Pass command", str(primary.get("acceptance") or "python -m pytest -q"), "",
            "## Stop conditions", "Primary DONE (window released automatically) or 3 same-cause failures.", ""]
    return "\n".join(out)


def open_companion_for(project: Path | str, primary_id: str, tool: str, *,
                       now: float | None = None) -> dict[str, Any] | None:
    """The companion `<primary>.<tool>` for one receiving tool: reused if open, created (or QUEUED at the cap) if not.

    No freshness check: a collaboration letter's receiver was already resolved ACTIVE by deliver. None if the primary
    has no nav record or the tool owns the primary.
    """
    project = Path(project)
    tool = canonical(tool)
    moment = time.time() if now is None else now
    primary = read_card(project, primary_id) if CARD_ID_RE.fullmatch(primary_id or "") else None
    if not primary or "." in primary_id or primary.get("state") == "DONE":
        return None  # a finished primary opens no new companion window
    primary_tool = (primary.get("owner") or {}).get("tool")
    if tool == primary_tool or tool not in TOOLS:
        return None
    cid = f"{primary_id}.{short(tool)}"
    cards = list_cards(project)
    current = next((c for c in cards if c["id"] == cid and c.get("state") != "DONE"), None)
    if current:
        return current
    others = [t for t in TOOLS if t != primary_tool]
    record = _create_companion(project, primary, tool, others.index(tool), moment, cards)
    links = sorted(set(primary.get("companions") or []) | {cid})
    write_card(project, primary_id, primary_tool, companions=links, now=moment)
    return record


def ensure_companion_window(project: Path | str, card: str, tool: str, actor: str = "", *,
                            runner: Any = None, rpc: Any = None, now: float | None = None) -> dict[str, Any]:
    """U331-A: a collaboration letter for `card` to `tool` opens (or reuses) that tool's companion window.

    Returns {"window": <id>, "companion": <ID>, "reused": bool} when the letter should be injected into that window, or
    {"skipped": <reason>} when it falls back to the tool's desk (no nav record, same tool, QUEUED at the 3-cap,
    refused or failed launch). Never raises, so a window problem cannot lose the letter.
    """
    from . import windows

    project = Path(project)
    tool = canonical(tool)
    try:
        if canonical(actor) == tool:
            return {"skipped": "SAME_TOOL"}
        companion = open_companion_for(project, str(card).split(".")[0], tool, now=now)
        if not companion:
            return {"skipped": "NO_NAV_PRIMARY"}
        cid = companion["id"]
        if companion.get("state") == "QUEUED":
            return {"skipped": "QUEUED_AT_CAP", "companion": cid}
        entry = windows.window_entry(project, cid, tool)
        if entry and windows._is_entry_active(entry):
            if tool == "codex":
                # U331-F: a reused Codex companion is verified like any card window; a stale or foreign thread is released
                # and the letter takes the tool's desk route (never injected into a thread of another project).
                from . import deliver
                bad = deliver._verify_thread(project, deliver._codex_sessions(), str(entry["id"]))
                if bad != "DISPATCH":
                    deliver._release_stale_card_window(project, cid, str(entry["id"]), bad)
                    return {"skipped": f"COMPANION_{bad}", "companion": cid}
            return {"window": str(entry["id"]), "companion": cid, "reused": True}
        opened = windows.open_window(project, cid, tool, str(companion.get("title") or cid),
                                     companion_manual(project, companion), runner=runner, rpc=rpc, now=now)
        if not opened.get("id"):
            return {"skipped": str(opened.get("refused") or "OPEN_FAILED"), "companion": cid}
        write_card(project, cid, tool, owner={"session": str(opened["id"])}, state="RUNNING", now=now)
        return {"window": str(opened["id"]), "companion": cid, "reused": bool(opened.get("reused"))}
    except Exception as exc:  # noqa: BLE001
        return {"skipped": f"ERROR {type(exc).__name__}: {exc}"[:200]}


# ---------------------------------------------------------------- per-tool hook line

def _due(card: dict[str, Any], now: float) -> str:
    deadlines = [w.get("deadline_at") for w in card.get("waits") or [] if isinstance(w.get("deadline_at"), (int, float))]
    return f", due {max(0, int(min(deadlines) - now))}s" if deadlines else ""


def _action(card: dict[str, Any], tool: str) -> str:
    nxt = card.get("next_action")
    if isinstance(nxt, dict):
        return str(nxt.get(short(tool)) or nxt.get(tool) or "")
    return str(nxt or "")


def hook_lines(project: Path | str, tool: str, *, now: float | None = None,
               seen: dict[str, str] | None = None) -> tuple[list[str], dict[str, str]]:
    """Only this tool's nav deltas, e.g. `nav: U329 RUNNING(claude) -> you(agy) U329.agy: counterexample audit, due 120s`.

    `seen` maps card id -> signature of the last line shown; a line is shown only when its signature changed
    (the due countdown is excluded so it does not re-fire every prompt). Returns (lines, new_seen).
    """
    tool = canonical(tool)
    moment = time.time() if now is None else now
    cards = {c["id"]: c for c in list_cards(project)}
    seen = dict(seen or {})
    new_seen: dict[str, str] = {}
    lines: list[str] = []
    for card in cards.values():
        owner = (card.get("owner") or {}).get("tool")
        state = effective_state(card, moment)
        if card.get("nature") == "companion":
            continue  # shown through its primary
        mine = [cards[c] for c in card.get("companions") or [] if c in cards
                and (cards[c].get("owner") or {}).get("tool") == tool and cards[c].get("state") != "DONE"]
        if owner != tool and not mine:
            continue
        if state == "DONE":
            continue
        if state == "UNKNOWN":
            age = int(moment - float(card.get("last_signal_at") or 0))
            sig = f"{card['id']}|UNKNOWN"
            line = f"nav: {card['id']} UNKNOWN({short(owner or '?')}) no signal {age}s, not actionable"
        elif owner == tool:
            act = _action(card, tool)
            sig = f"{card['id']}|{state}|{act}|{card.get('plan_rev')}"
            line = f"nav: {card['id']} {state}(you)" + (f" next: {act}" if act else "")
        else:
            comp = mine[0]
            cstate = effective_state(comp, moment)
            act = _action(comp, tool)
            sig = f"{card['id']}|{state}|{comp['id']}|{cstate}|{act}|{comp.get('plan_rev')}"
            if cstate == "UNKNOWN":
                line = f"nav: {card['id']} {state}({short(owner or '?')}) -> you({short(tool)}) {comp['id']}: UNKNOWN, not actionable"
            elif cstate == "QUEUED":
                line = f"nav: {card['id']} {state}({short(owner or '?')}) -> you({short(tool)}) {comp['id']}: QUEUED behind {MAX_OPEN_COMPANIONS} open"
            else:
                line = (f"nav: {card['id']} {state}({short(owner or '?')}) -> you({short(tool)}) {comp['id']}: "
                        f"{act.split(';')[0]}{_due(comp, moment)}")
        if seen.get(card["id"]) == sig:
            new_seen[card["id"]] = sig  # already shown
        elif len(lines) < MAX_HOOK_LINES:
            lines.append(line)
            new_seen[card["id"]] = sig
        elif card["id"] in seen:
            new_seen[card["id"]] = seen[card["id"]]  # over the cap: keep the old signature so it fires next prompt
    return lines, new_seen
