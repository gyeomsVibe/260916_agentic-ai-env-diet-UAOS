"""Install UAOS for every project on this PC (U37). Dry run by default; `--apply` writes, `--check` reports drift.

What it installs (the user approved B77 on 2026-09-25):
1. A launcher `~/.uaos/uaos.py`, so `python ~/.uaos/uaos.py <command>` runs this repository's harness from any folder.
2. A marked rule block in each tool's global rules: ~/.claude/CLAUDE.md, ~/.codex/AGENTS.md, ~/.gemini/GEMINI.md.
3. Presence (attendance) hooks: Claude ~/.claude/settings.json, Codex ~/.codex/hooks.json (+ `codex_hooks = true`),
   Antigravity ~/.gemini/config/hooks.json. They do nothing outside a UAOS project (no `.coord/PLAN.md` above cwd).
4. The paid-scheduler block for Claude: `permissions.deny` for CronCreate, ScheduleWakeup and the remote triggers.
5. Optional, Windows only: the 24/7 sentinel for one project (`--register-sentinel PROJECT`), a logon task that
   starts `coord sentinel --loop` under pythonw. It makes no model calls.

Safety: every file is copied to ~/.uaos-backups/<time>/ before it changes; a JSON file that does not parse is left
alone; only UAOS's own entries are replaced or removed (`--uninstall`), everything else in those files stays.
The three rule files are generated by the global-rules canon (shared/global-rules, sync-global-rules.ps1). A block
written here is removed by that generator's next Apply unless the canon carries it too; `--check` shows that drift.
"""

